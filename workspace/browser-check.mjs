import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const base=process.env.AXTHENA_URL??'http://127.0.0.1:17780';
const browser=await chromium.launch({channel:'chromium',headless:true});
const page=await browser.newPage({viewport:{width:1512,height:1100},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.goto(base);
await page.getByRole('button',{name:'Explore an activity'}).waitFor();
await page.waitForFunction(()=>document.querySelectorAll('.metric strong')[0]?.textContent!=='0');
assert.ok(await page.getByRole('region',{name:'AI investigation chat'}).isVisible());
await page.getByRole('button',{name:'Explore an activity'}).click();
await page.locator('.quotation blockquote').first().waitFor();
assert.ok(await page.locator('.quotation blockquote').count()>0);
await page.getByRole('button',{name:'Show overview'}).click();
await mkdir('../docs/images',{recursive:true});
await page.screenshot({path:'../docs/images/workspace.png',fullPage:true});
await page.getByRole('button',{name:'Records',exact:true}).click();
await page.locator('.record').first().click();
assert.ok(await page.locator('.inspector-content h3').textContent());
await page.getByRole('button',{name:'Save view'}).click();
assert.equal(await page.locator('.saved').count(),1);
await page.getByRole('button',{name:'Judgments',exact:false}).first().click();
await page.getByRole('heading',{name:'No eligible records'}).waitFor();
await page.getByRole('button',{name:'Overview',exact:false}).first().click();
await page.locator('.network').waitFor();
// Test the conversation against real model transport when explicitly requested.
if(process.env.AXTHENA_LIVE_AI==='1'){
 await page.getByRole('textbox',{name:'Message Axthena'}).fill('What opinions are reported about NVIDIA?');
 await page.getByRole('button',{name:'Send ↑'}).click();
 await page.locator('.chat-turn.assistant .query-receipt').first().waitFor({timeout:300000});
 assert.equal(await page.locator('.chat-turn.assistant').count(),1);
 assert.ok(await page.locator('.chat-citation').count()>0);
 await page.getByRole('textbox',{name:'Message Axthena'}).fill('Now only Microsoft, keeping the same information type and dates.');
 await page.getByRole('button',{name:'Send ↑'}).click();
 await page.locator('.chat-turn.assistant .query-receipt').nth(1).waitFor({timeout:300000});
 assert.match(await page.locator('.chat-turn.assistant .query-receipt').nth(1).textContent(),/MSFT.US/);
 await page.locator('.chat-citation').first().click();
 await page.locator('.quotation blockquote').first().waitFor();
 assert.match(await page.locator('.heading h1').textContent(),/NVIDIA/);
 await page.getByRole('textbox',{name:'Message Axthena'}).fill('Show the source for the selected record.');
 await page.getByRole('button',{name:'Send ↑'}).click();
 await page.locator('.chat-turn.assistant .query-receipt').nth(2).waitFor({timeout:300000});
 assert.match(await page.locator('.chat-turn.assistant .query-receipt').nth(2).textContent(),/evidence/);
 await page.locator('.chat-citation').last().click();
 await page.locator('.quotation blockquote').first().waitFor();
 await page.locator('.chat-messages').evaluate(e=>{e.scrollTop=e.scrollHeight;});
 await page.screenshot({path:'../docs/images/chat.png',fullPage:true});
}
assert.deepEqual(errors,[]);
await browser.close();
console.log('PASS live browser: data, chat panel, evidence, graph focus, records, save, judgment empty state'+(process.env.AXTHENA_LIVE_AI==='1'?', model queries, follow-up scope, citation restore':''));
