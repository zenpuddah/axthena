import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chromium',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const failures=[];page.on('pageerror',e=>failures.push(String(e)));
const base=process.env.AXTHENA_URL??'http://127.0.0.1:17780';
await page.goto(base+'/?demo=1');
await page.waitForFunction(()=>document.querySelectorAll('.metric strong')[0]?.textContent==='23');
await page.getByRole('button',{name:'Explore an activity'}).click();
await page.locator('.quotation').first().waitFor();
assert.ok(await page.getByRole('button',{name:'Send ↑'}).isDisabled());
await page.getByRole('combobox',{name:'Company',exact:true}).selectOption('MSFT.US');
await page.getByRole('button',{name:'Apply filters'}).click();
await page.waitForFunction(()=>document.querySelector('.heading h1')?.textContent?.includes('Microsoft'));
await page.getByRole('button',{name:'Compare',exact:false}).first().click();
await page.locator('.comparison').waitFor();
assert.equal(await page.locator('.comparison>div:not(.panel-heading)').count(),2);
await page.getByRole('combobox',{name:'Time basis'}).selectOption('strict');
await page.getByRole('button',{name:'Apply filters'}).click();
await page.getByRole('heading',{name:'No eligible records'}).waitFor();
assert.deepEqual(failures,[]);
await browser.close();console.log('PASS offline snapshots: NVIDIA, Microsoft, compare, evidence, strict empty and explicit chat unavailability');
